package app.unocontrol;

/** Offline, author-reviewed notes. New entries can be added without touching GitHub data or tokens. */
final class DeveloperNotes {
    static final class Section {
        final String title;
        final String text;
        Section(String title, String text) { this.title = title; this.text = text; }
    }
    static final class Entry {
        final String title;
        final String subtitle;
        final Section[] sections;
        Entry(String title, String subtitle, Section... sections) {
            this.title = title;
            this.subtitle = subtitle;
            this.sections = sections;
        }
    }

    private static final Entry[] ENTRIES = {
        new Entry("Не доверяйте ИИ на слово", "Заметка №1 · Личный опыт разработчика GitTeller",
            new Section("Почему я об этом говорю",
                "Я разрабатываю проекты с помощью нескольких ИИ-агентов. Они действительно ускоряют работу. Но есть ловушка: агент может очень уверенно рассказать, что всё исправил, хотя код не собирается, файл не сохранён или проверка не проводилась. Красивый отчёт не равен работающей программе."),
            new Section("Проверяйте результат, а не уверенность",
                "Просите показать точную ветку и SHA коммита, изменённые файлы, результат сборки и тестов. Если приложение для телефона, проверяйте его на телефоне. Коммит доказывает, что код записан, но не доказывает, что программа работает. Если тест не запускали, правильный ответ: «не проверено»."),
            new Section("Как я работаю с несколькими ИИ без API",
                "Мне не нужна сложная система, которая автоматически гоняет запросы между моделями. Я использую GitHub как общую точку сохранения работы, а задачи передаю вручную.\n\n"
                + "1. Одному агенту даю чёткое задание: что изменить и что не трогать.\n"
                + "2. Прошу сохранить результат в правильной ветке и назвать SHA.\n"
                + "3. Другому агенту передаю ссылку на этот коммит или diff и прошу найти ошибки, а не похвалить работу.\n"
                + "4. Первый исправляет подтверждённые проблемы. При споре требую код, логи и воспроизводимый пример.\n"
                + "5. Сам проверяю то, что нельзя доказать из чата: установку, интерфейс, сохранность данных и реальное поведение приложения.\n\n"
                + "Это не полная автоматизация. Это простой повторяемый процесс без платного API. GitTeller помогает наблюдать за изменениями в GitHub, но не заменяет испытания."),
            new Section("Как формулировать задания",
                "Вместо «сделай красиво и исправь всё» полезнее писать: «Проверь текущие ветку и HEAD. Прочитай правила проекта. Измени только нужную функцию. Не удаляй данные, не переписывай историю. Покажи diff, тесты и то, что не проверено». Чем понятнее границы, тем меньше шанс, что агент устроит незапланированный ремонт всего проекта."),
            new Section("Не отдавайте агентам лишнюю власть",
                "Не отправляйте ИИ пароли и токены. Не давайте права на удаление, публикацию или запуск платных ресурсов без необходимости. Храните исходники, прежние сборки и возможность отката. Пускай агенты спорят с вашими решениями, если у них есть доказательства: соглашательство не помогает найти ошибку."),
            new Section("Мой главный совет",
                "Используйте несколько ИИ как исполнителей и независимых проверяющих, а не как непререкаемых экспертов. Решение принимаете вы. Спрашивайте не «ты закончил?», а «где результат и чем он подтверждён?». Этим опытом я собираюсь делиться и дальше.")
        )
    };

    private DeveloperNotes() {}
    static Entry[] all() { return ENTRIES.clone(); }
    static Entry at(int index) { return index >= 0 && index < ENTRIES.length ? ENTRIES[index] : null; }
}
